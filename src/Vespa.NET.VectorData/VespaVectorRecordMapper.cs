using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text.Json;
using Microsoft.Extensions.VectorData;

namespace Vespa.VectorData;

internal sealed class VespaVectorRecordMapper<TRecord> where TRecord : class
{
    private readonly MappedProperty _key;
    private readonly MappedProperty[] _properties;
    private readonly ConstructorInfo? _constructor;
    private readonly HashSet<string> _requiredDataFields;

    internal VespaVectorRecordMapper(VectorStoreCollectionDefinition? definition, IReadOnlyCollection<string> requiredDataFields)
    {
        IsDynamic = typeof(TRecord) == typeof(Dictionary<string, object?>);
        if (IsDynamic && definition is null)
            throw new ArgumentNullException(nameof(definition), "Dynamic collections require an explicit record definition.");
        if (!IsDynamic)
            _constructor = typeof(TRecord).GetConstructor(Type.EmptyTypes)
                ?? throw new NotSupportedException("Records must have a public parameterless constructor and writable mapped properties.");
        var definitions = (definition?.Properties ?? DiscoverProperties()).ToArray();
        if (definitions.Select(p => p.Name).Distinct(StringComparer.Ordinal).Count() != definitions.Length)
            throw new ArgumentException("Each record property must have exactly one mapping role.", nameof(definition));
        var keys = definitions.OfType<VectorStoreKeyProperty>().ToArray();
        var vectors = definitions.OfType<VectorStoreVectorProperty>().ToArray();
        if (keys.Length != 1 || keys[0].IsAutoGenerated == true)
            throw new NotSupportedException("Exactly one caller-assigned string or Guid key is required.");
        _key = ResolveProperty(keys[0]);
        if (_key.Type != typeof(string) && _key.Type != typeof(Guid))
            throw new NotSupportedException("Exactly one caller-assigned string or Guid key is required.");
        if (vectors.Length != 1)
            throw new NotSupportedException("The provider supports exactly one dense vector property per collection.");
        var vector = vectors[0];
        var vectorType = ResolveProperty(vector).Type;
        if (vectorType != typeof(ReadOnlyMemory<float>) && vectorType != typeof(float[]) && !(IsDynamic && vectorType == typeof(string)))
            throw new NotSupportedException("Vector properties must be ReadOnlyMemory<float> or float[]; dynamic collections also accept string inputs for embedding generation.");
        if (vector.DistanceFunction is not null && vector.DistanceFunction != DistanceFunction.CosineSimilarity)
            throw new NotSupportedException("The provider supports CosineSimilarity over a Vespa angular tensor field.");
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(vector.Dimensions);
        Dimensions = vector.Dimensions;
        _properties = definitions.Where(p => p is not VectorStoreKeyProperty).Select(p =>
        {
            if (p is not VectorStoreDataProperty and not VectorStoreVectorProperty)
                throw new NotSupportedException($"Unsupported property definition '{p.GetType().Name}'.");
            var property = ResolveProperty(p);
            if (p is VectorStoreDataProperty && !IsSupportedDataType(property.Type))
                throw new NotSupportedException($"Data property '{p.Name}' must be a supported scalar or scalar array; nested object mapping is not implemented.");
            VespaVectorValidation.Identifier(property.StorageName, nameof(definition));
            if (property.StorageName == "documentid")
                throw new ArgumentException("'documentid' is reserved for Vespa document identity.", nameof(definition));
            return property;
        }).ToArray();
        if (_properties.Select(p => p.StorageName).Distinct(StringComparer.Ordinal).Count() != _properties.Length)
            throw new ArgumentException("Mapped storage field names must be unique.", nameof(definition));
        VectorProperty = _properties.Single(p => p.IsVector);
        _requiredDataFields = requiredDataFields.ToHashSet(StringComparer.Ordinal);
        foreach (var property in _properties.Where(p => !p.IsVector && p.Property?.IsDefined(typeof(RequiredMemberAttribute)) == true))
            _requiredDataFields.Add(property.StorageName);
        foreach (var name in _requiredDataFields)
            if (!_properties.Any(p => !p.IsVector && p.StorageName == name))
                throw new ArgumentException($"Required data field '{name}' must be a mapped data storage field.", nameof(requiredDataFields));
    }

    internal bool IsDynamic { get; }
    internal Type KeyType => _key.Type;
    internal int Dimensions { get; }
    internal MappedProperty VectorProperty { get; }
    internal bool GeneratesVectors => VectorProperty.Type == typeof(string);

    internal string Projection(bool includeVectors) => string.Join(", ",
        _properties.Where(p => includeVectors || !p.IsVector).Select(p => p.StorageName).Prepend("documentid"));

    internal string FieldSet(string schema, bool includeVectors)
    {
        var fields = _properties.Where(p => includeVectors || !p.IsVector).Select(p => p.StorageName).ToArray();
        return fields.Length == 0 ? "[id]" : $"{schema}:{string.Join(',', fields)}";
    }

    internal string GetKey(TRecord record) => FormatKey(GetValue(record, _key), nameof(record));

    internal string FormatKey(object? key, string parameterName = "key")
    {
        if (KeyType == typeof(string) && key is string text && !string.IsNullOrWhiteSpace(text))
            return text;
        if (KeyType == typeof(Guid) && key is Guid guid)
            return guid.ToString("D");
        throw new ArgumentException($"The key must be a nonempty value of type '{KeyType.Name}'.", parameterName);
    }

    internal Dictionary<string, object?> ToFields(TRecord record)
    {
        ArgumentNullException.ThrowIfNull(record);
        if (IsDynamic)
            foreach (var name in ((Dictionary<string, object?>)(object)record).Keys)
                if (name != _key.Name && !_properties.Any(p => p.Name == name))
                    throw new ArgumentException($"Record field '{name}' has no mapping in the collection definition.", nameof(record));
        var fields = new Dictionary<string, object?>(StringComparer.Ordinal);
        foreach (var property in _properties)
        {
            var value = GetValue(record, property);
            if (value is null)
            {
                if (property.IsVector)
                    throw new ArgumentException("A vector or text to embed is required when upserting a record.", nameof(record));
                if (_requiredDataFields.Contains(property.StorageName))
                    throw new ArgumentException($"Required data field '{property.StorageName}' cannot be null or absent.", nameof(record));
                continue;
            }
            if (property.IsVector)
            {
                if (value is string && GeneratesVectors)
                {
                    fields.Add(property.StorageName, value);
                    continue;
                }
                var values = value switch
                {
                    float[] array => (float[])array.Clone(),
                    ReadOnlyMemory<float> memory => memory.ToArray(),
                    _ => throw new ArgumentException($"Vector field '{property.Name}' must contain a float vector or a configured string input.", nameof(record))
                };
                ValidateVector(values);
                value = Tensor(values);
            }
            else if (!(Nullable.GetUnderlyingType(property.Type) ?? property.Type).IsInstanceOfType(value))
                throw new ArgumentException($"Record field '{property.Name}' must have type '{property.Type}'.", nameof(record));
            else if (value is Array array)
                value = array.Clone();
            fields.Add(property.StorageName, value);
        }
        return fields;
    }

    internal TRecord FromFields(string key, Dictionary<string, JsonElement> fields, bool includeVectors)
    {
        if (includeVectors && (!fields.TryGetValue(VectorProperty.StorageName, out var tensor) || tensor.ValueKind is JsonValueKind.Null or JsonValueKind.Undefined))
            throw new VectorStoreException($"Requested vector field '{VectorProperty.StorageName}' is missing or null. Select a summary/field set containing the vector.");
        foreach (var name in _requiredDataFields)
            if (!fields.TryGetValue(name, out var value) || value.ValueKind is JsonValueKind.Null or JsonValueKind.Undefined)
                throw new VectorStoreException($"Required data field '{name}' is missing or null. Check the stored data and selected summary/field set.");
        var record = IsDynamic ? (TRecord)(object)new Dictionary<string, object?>(StringComparer.Ordinal) : (TRecord)_constructor!.Invoke(null);
        object identity = key;
        if (KeyType == typeof(Guid))
        {
            if (!Guid.TryParseExact(key, "D", out var guid) || guid.ToString("D") != key)
                throw new VectorStoreException("A Guid key requires a canonical lowercase D-format document ID.");
            identity = guid;
        }
        SetValue(record, _key, identity);
        if (!IsDynamic && !includeVectors)
            SetValue(record, VectorProperty, VectorProperty.Type == typeof(float[]) ? null : (object)ReadOnlyMemory<float>.Empty);
        foreach (var property in _properties)
        {
            if ((!includeVectors && property.IsVector) || !fields.TryGetValue(property.StorageName, out var value))
                continue;
            object? mapped;
            if (property.IsVector && value.ValueKind != JsonValueKind.Null)
            {
                if (value.ValueKind == JsonValueKind.Object && !value.TryGetProperty("values", out value))
                    throw new VectorStoreException($"Expected a dense tensor values array for '{property.StorageName}'.");
                var vector = value.Deserialize<float[]>()
                    ?? throw new VectorStoreException($"Missing dense tensor values for '{property.StorageName}'.");
                try
                {
                    ValidateVector(vector);
                }
                catch (ArgumentException exception)
                {
                    throw new VectorStoreException($"Invalid stored vector in '{property.StorageName}'.", exception);
                }
                mapped = property.Type == typeof(float[]) ? (object)vector : new ReadOnlyMemory<float>(vector);
            }
            else
                mapped = value.Deserialize(property.Type);
            SetValue(record, property, mapped);
        }
        return record;
    }

    internal void ValidateVector(ReadOnlySpan<float> vector)
    {
        if (vector.Length != Dimensions)
            throw new ArgumentException($"Expected {Dimensions} vector dimensions, received {vector.Length}.", nameof(vector));
        var nonzero = false;
        foreach (var value in vector)
        {
            if (!float.IsFinite(value))
                throw new ArgumentException("Vectors must contain only finite values.", nameof(vector));
            nonzero |= value != 0;
        }
        if (!nonzero)
            throw new ArgumentException("A cosine-similarity vector cannot be zero.", nameof(vector));
    }

    internal MappedProperty DataProperty(string name) => _properties.SingleOrDefault(p =>
        p.Name == name && p.IsFilterable && !p.Type.IsArray)
        ?? throw new NotSupportedException($"Filtering on '{name}' is unsupported; use a scalar data property marked IsIndexed.");

    internal MappedProperty Property(string name) => _properties.SingleOrDefault(p => p.Name == name)
        ?? throw new NotSupportedException($"Record field '{name}' is not mapped.");

    internal static Dictionary<string, object> Tensor(float[] values) => new() { ["values"] = values };

    private object? GetValue(TRecord record, MappedProperty property) => IsDynamic
        ? ((Dictionary<string, object?>)(object)record).GetValueOrDefault(property.Name)
        : property.Property!.GetValue(record);

    private void SetValue(TRecord record, MappedProperty property, object? value)
    {
        if (IsDynamic)
            ((Dictionary<string, object?>)(object)record)[property.Name] = value;
        else
            property.Property!.SetValue(record, value);
    }

    private MappedProperty ResolveProperty(VectorStoreProperty definition)
    {
        PropertyInfo? property = null;
        Type type;
        if (IsDynamic)
            type = definition.Type ?? throw new ArgumentException($"Dynamic property '{definition.Name}' must declare its CLR type.", nameof(definition));
        else
        {
            property = typeof(TRecord).GetProperty(definition.Name, BindingFlags.Public | BindingFlags.Instance);
            if (property is null || (definition.Type is { } declaredType && property.PropertyType != declaredType) ||
                property.GetMethod?.IsPublic != true || property.SetMethod?.IsPublic != true || property.GetIndexParameters().Length != 0)
                throw new ArgumentException($"'{definition.Name}' must identify a public readable/writable property of type '{definition.Type}'.");
            type = property.PropertyType;
        }
        return new(definition.Name, type, property, definition.StorageName ?? definition.Name,
            definition is VectorStoreVectorProperty, definition is VectorStoreDataProperty { IsIndexed: true });
    }

    private static bool IsSupportedDataType(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        if (type.IsArray)
        {
            if (type.GetArrayRank() != 1)
                return false;
            type = type.GetElementType()!;
        }
        return type == typeof(string) || type == typeof(bool) || type == typeof(int) ||
            type == typeof(long) || type == typeof(float) || type == typeof(double);
    }

    private static List<VectorStoreProperty> DiscoverProperties()
    {
        List<VectorStoreProperty> result = [];
        foreach (var property in typeof(TRecord).GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.GetCustomAttribute<VectorStoreKeyAttribute>() is { } key)
                result.Add(new VectorStoreKeyProperty(property.Name, property.PropertyType)
                {
                    StorageName = key.StorageName,
                    IsAutoGenerated = key.IsAutoGenerated
                });
            if (property.GetCustomAttribute<VectorStoreDataAttribute>() is { } data)
                result.Add(new VectorStoreDataProperty(property.Name, property.PropertyType)
                {
                    StorageName = data.StorageName,
                    IsIndexed = data.IsIndexed,
                    IsFullTextIndexed = data.IsFullTextIndexed
                });
            if (property.GetCustomAttribute<VectorStoreVectorAttribute>() is { } vector)
                result.Add(new VectorStoreVectorProperty(property.Name, property.PropertyType, vector.Dimensions)
                {
                    StorageName = vector.StorageName,
                    DistanceFunction = vector.DistanceFunction,
                    IndexKind = vector.IndexKind
                });
        }
        return result;
    }

    internal sealed record MappedProperty(string Name, Type Type, PropertyInfo? Property, string StorageName, bool IsVector, bool IsFilterable);
}
