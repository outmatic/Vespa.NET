using System.Reflection;
using System.Text.Json;
using Microsoft.Extensions.VectorData;
using Vespa.Models;

namespace Vespa.VectorData;

internal sealed class VespaVectorRecordMapper<TRecord> where TRecord : class
{
    private readonly PropertyInfo _key;
    private readonly MappedProperty[] _properties;
    private readonly ConstructorInfo _constructor;

    internal VespaVectorRecordMapper(VectorStoreCollectionDefinition? definition)
    {
        _constructor = typeof(TRecord).GetConstructor(Type.EmptyTypes)
            ?? throw new NotSupportedException("Records must have a public parameterless constructor and writable mapped properties.");
        var definitions = definition?.Properties ?? DiscoverProperties();
        if (definitions.Select(p => p.Name).Distinct(StringComparer.Ordinal).Count() != definitions.Count)
            throw new ArgumentException("Each CLR property must have exactly one mapping role.", nameof(definition));
        var keys = definitions.OfType<VectorStoreKeyProperty>().ToArray();
        var vectors = definitions.OfType<VectorStoreVectorProperty>().ToArray();
        if (keys.Length != 1 || keys[0].IsAutoGenerated == true)
            throw new NotSupportedException("Exactly one caller-assigned string key is required.");
        _key = ResolveProperty(keys[0]);
        if (_key.PropertyType != typeof(string))
            throw new NotSupportedException("Exactly one caller-assigned string key is required.");
        if (vectors.Length != 1)
            throw new NotSupportedException("The provider supports exactly one dense vector property per collection.");
        var vector = vectors[0];
        var vectorType = ResolveProperty(vector).PropertyType;
        if (vectorType != typeof(ReadOnlyMemory<float>) && vectorType != typeof(float[]))
            throw new NotSupportedException("Vector properties must be ReadOnlyMemory<float> or float[].");
        if (vector.DistanceFunction is not null && vector.DistanceFunction != DistanceFunction.CosineSimilarity)
            throw new NotSupportedException("The provider supports CosineSimilarity over a Vespa angular tensor field.");
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(vector.Dimensions);
        Dimensions = vector.Dimensions;
        _properties = definitions.Where(p => p is not VectorStoreKeyProperty).Select(p =>
        {
            if (p is not VectorStoreDataProperty and not VectorStoreVectorProperty)
                throw new NotSupportedException($"Unsupported property definition '{p.GetType().Name}'.");
            var property = ResolveProperty(p);
            if (p is VectorStoreDataProperty && !IsSupportedDataType(property.PropertyType))
                throw new NotSupportedException($"Data property '{p.Name}' must be a supported scalar or scalar array; nested object mapping is not implemented.");
            var name = p.StorageName ?? p.Name;
            VespaVectorValidation.Identifier(name, nameof(definition));
            if (name == "documentid")
                throw new ArgumentException("'documentid' is reserved for Vespa document identity.", nameof(definition));
            return new MappedProperty(property, name, p is VectorStoreVectorProperty,
                p is VectorStoreDataProperty { IsIndexed: true });
        }).ToArray();
        if (_properties.Select(p => p.StorageName).Distinct(StringComparer.Ordinal).Count() != _properties.Length)
            throw new ArgumentException("Mapped storage field names must be unique.", nameof(definition));
        VectorProperty = _properties.Single(p => p.IsVector);
    }

    internal int Dimensions { get; }
    internal MappedProperty VectorProperty { get; }

    internal string Projection(bool includeVectors) => string.Join(", ",
        _properties.Where(p => includeVectors || !p.IsVector).Select(p => p.StorageName).Prepend("documentid"));

    internal string GetKey(TRecord record)
    {
        var key = (string?)_key.GetValue(record);
        ArgumentException.ThrowIfNullOrWhiteSpace(key, nameof(record));
        return key;
    }

    internal Dictionary<string, object?> ToFields(TRecord record)
    {
        ArgumentNullException.ThrowIfNull(record);
        var fields = new Dictionary<string, object?>(StringComparer.Ordinal);
        foreach (var property in _properties)
        {
            var value = property.Property.GetValue(record);
            if (value is null)
            {
                if (property.IsVector)
                    throw new ArgumentException("A vector is required when upserting a record.", nameof(record));
                continue;
            }
            if (property.IsVector)
            {
                var vector = value is float[] array ? array : ((ReadOnlyMemory<float>)value).ToArray();
                ValidateVector(vector);
                value = new Dictionary<string, object> { ["values"] = vector };
            }
            fields.Add(property.StorageName, value);
        }
        return fields;
    }

    internal TRecord FromFields(string key, Dictionary<string, JsonElement> fields, bool includeVectors)
    {
        var record = (TRecord)_constructor.Invoke(null);
        _key.SetValue(record, key);
        VectorProperty.Property.SetValue(record, VectorProperty.Property.PropertyType == typeof(float[])
            ? null : (object)ReadOnlyMemory<float>.Empty);
        foreach (var property in _properties)
        {
            if ((!includeVectors && property.IsVector) || !fields.TryGetValue(property.StorageName, out var value))
                continue;
            object? mapped;
            if (property.IsVector && value.ValueKind != JsonValueKind.Null)
            {
                if (value.ValueKind == JsonValueKind.Object && !value.TryGetProperty("values", out value))
                    throw new VectorStoreException($"Expected a dense tensor values array for '{property.StorageName}'.");
                var vector = value.Deserialize<float[]>()
                    ?? throw new VectorStoreException($"Missing dense tensor values for '{property.StorageName}'.");
                try
                {
                    ValidateVector(vector);
                }
                catch (ArgumentException exception)
                {
                    throw new VectorStoreException($"Invalid stored vector in '{property.StorageName}'.", exception);
                }
                mapped = property.Property.PropertyType == typeof(float[]) ? (object)vector : new ReadOnlyMemory<float>(vector);
            }
            else
                mapped = value.Deserialize(property.Property.PropertyType);
            property.Property.SetValue(record, mapped);
        }
        return record;
    }

    internal void ValidateVector(ReadOnlySpan<float> vector)
    {
        if (vector.Length != Dimensions)
            throw new ArgumentException($"Expected {Dimensions} vector dimensions, received {vector.Length}.", nameof(vector));
        var nonzero = false;
        foreach (var value in vector)
        {
            if (!float.IsFinite(value))
                throw new ArgumentException("Vectors must contain only finite values.", nameof(vector));
            nonzero |= value != 0;
        }
        if (!nonzero)
            throw new ArgumentException("A cosine-similarity vector cannot be zero.", nameof(vector));
    }

    internal MappedProperty DataProperty(string name) => _properties.SingleOrDefault(p =>
        p.Property.Name == name && p.IsFilterable && !p.Property.PropertyType.IsArray)
        ?? throw new NotSupportedException($"Filtering on '{name}' is unsupported; use a scalar data property marked IsIndexed.");

    private static PropertyInfo ResolveProperty(VectorStoreProperty definition)
    {
        var property = typeof(TRecord).GetProperty(definition.Name, BindingFlags.Public | BindingFlags.Instance);
        if (property is null || (definition.Type is { } declaredType && property.PropertyType != declaredType) ||
            property.GetMethod?.IsPublic != true || property.SetMethod?.IsPublic != true || property.GetIndexParameters().Length != 0)
            throw new ArgumentException($"'{definition.Name}' must identify a public readable/writable property of type '{definition.Type}'.");
        return property;
    }

    private static bool IsSupportedDataType(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        if (type.IsArray)
        {
            if (type.GetArrayRank() != 1)
                return false;
            type = type.GetElementType()!;
        }
        return type == typeof(string) || type == typeof(bool) || type == typeof(int) ||
            type == typeof(long) || type == typeof(float) || type == typeof(double);
    }

    private static List<VectorStoreProperty> DiscoverProperties()
    {
        List<VectorStoreProperty> result = [];
        foreach (var property in typeof(TRecord).GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.GetCustomAttribute<VectorStoreKeyAttribute>() is { } key)
                result.Add(new VectorStoreKeyProperty(property.Name, property.PropertyType)
                {
                    StorageName = key.StorageName,
                    IsAutoGenerated = key.IsAutoGenerated
                });
            if (property.GetCustomAttribute<VectorStoreDataAttribute>() is { } data)
                result.Add(new VectorStoreDataProperty(property.Name, property.PropertyType)
                {
                    StorageName = data.StorageName,
                    IsIndexed = data.IsIndexed,
                    IsFullTextIndexed = data.IsFullTextIndexed
                });
            if (property.GetCustomAttribute<VectorStoreVectorAttribute>() is { } vector)
                result.Add(new VectorStoreVectorProperty(property.Name, property.PropertyType, vector.Dimensions)
                {
                    StorageName = vector.StorageName,
                    DistanceFunction = vector.DistanceFunction,
                    IndexKind = vector.IndexKind
                });
        }
        return result;
    }

    internal sealed record MappedProperty(PropertyInfo Property, string StorageName, bool IsVector, bool IsFilterable);
}
