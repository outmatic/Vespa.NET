using System.Collections;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text.Json;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.VectorData;

namespace Vespa.VectorData;

/// <summary>The validated, immutable mapping shared by document and query operations.</summary>
internal sealed class VespaCollectionModel
{
    private VespaCollectionModel(bool isDynamic, ConstructorInfo? constructor, MappedProperty key,
        MappedProperty[] properties, HashSet<string> requiredDataFields)
    {
        IsDynamic = isDynamic;
        Constructor = constructor;
        Key = key;
        Properties = Array.AsReadOnly(properties);
        VectorProperties = Array.AsReadOnly(properties.Where(p => p.IsVector).ToArray());
        RequiredDataFields = requiredDataFields;
    }

    internal bool IsDynamic { get; }
    internal ConstructorInfo? Constructor { get; }
    internal MappedProperty Key { get; }
    internal IReadOnlyList<MappedProperty> Properties { get; }
    internal IReadOnlyList<MappedProperty> VectorProperties { get; }
    internal IReadOnlySet<string> RequiredDataFields { get; }

    internal static VespaCollectionModel Build(Type recordType, VectorStoreCollectionDefinition? definition,
        IReadOnlyCollection<string> requiredDataFields, IEmbeddingGenerator? defaultEmbeddingGenerator = null)
    {
        var isDynamic = recordType == typeof(Dictionary<string, object?>);
        if (isDynamic && definition is null)
            throw new ArgumentNullException(nameof(definition), "Dynamic collections require an explicit record definition.");
        var constructor = isDynamic ? null : recordType.GetConstructor(Type.EmptyTypes)
            ?? throw new NotSupportedException("Records must have a public parameterless constructor and writable mapped properties.");
        var definitions = (definition?.Properties ?? DiscoverProperties(recordType)).ToArray();
        if (definitions.Select(p => p.Name).Distinct(StringComparer.Ordinal).Count() != definitions.Length)
            throw new ArgumentException("Each record property must have exactly one mapping role.", nameof(definition));
        var keys = definitions.OfType<VectorStoreKeyProperty>().ToArray();
        if (keys.Length != 1 || keys[0].IsAutoGenerated == true)
            throw new NotSupportedException("Exactly one caller-assigned string, Guid, int, long or ulong key is required.");
        var generator = definition?.EmbeddingGenerator ?? defaultEmbeddingGenerator;
        var nullability = new NullabilityInfoContext();
        var key = ResolveProperty(recordType, isDynamic, keys[0], generator, nullability);
        if (key.Type != typeof(string) && key.Type != typeof(Guid) && key.Type != typeof(int) &&
            key.Type != typeof(long) && key.Type != typeof(ulong))
            throw new NotSupportedException("Keys must be string, Guid, int, long or ulong.");
        var properties = definitions.Where(p => p is not VectorStoreKeyProperty).Select(p =>
        {
            if (p is not VectorStoreDataProperty and not VectorStoreVectorProperty)
                throw new NotSupportedException($"Unsupported property definition '{p.GetType().Name}'.");
            var property = ResolveProperty(recordType, isDynamic, p, generator, nullability);
            VespaVectorValidation.Identifier(property.StorageName, nameof(definition));
            if (property.StorageName == "documentid")
                throw new ArgumentException("'documentid' is reserved for Vespa document identity.", nameof(definition));
            if (property.IsVector)
                ValidateVectorProperty(property, (VectorStoreVectorProperty)p, isDynamic);
            else if (!IsSupportedDataType(property.Type))
                throw new NotSupportedException($"Data property '{p.Name}' must be a supported scalar, scalar array or List<T>; nested object mapping is not implemented.");
            return property;
        }).ToArray();
        if (properties.Select(p => p.StorageName).Distinct(StringComparer.Ordinal).Count() != properties.Length)
            throw new ArgumentException("Mapped storage field names must be unique.", nameof(definition));
        var required = requiredDataFields.ToHashSet(StringComparer.Ordinal);
        foreach (var property in properties.Where(p => !p.IsVector && p.Property?.IsDefined(typeof(RequiredMemberAttribute)) == true))
            required.Add(property.StorageName);
        foreach (var name in required)
            if (!properties.Any(p => !p.IsVector && p.StorageName == name))
                throw new ArgumentException($"Required data field '{name}' must be a mapped data storage field.", nameof(requiredDataFields));
        return new(isDynamic, constructor, key, properties, required);
    }

    private static void ValidateVectorProperty(MappedProperty property, VectorStoreVectorProperty definition, bool isDynamic)
    {
        var type = Nullable.GetUnderlyingType(property.Type) ?? property.Type;
        if (type != typeof(ReadOnlyMemory<float>) && type != typeof(float[]) && type != typeof(Embedding<float>) && type != typeof(string))
            throw new NotSupportedException("Vector properties must be ReadOnlyMemory<float>, float[], Embedding<float>, or string inputs for embedding generation.");
        if (definition.EmbeddingType is { } embeddingType && embeddingType != typeof(Embedding<float>))
            throw new NotSupportedException("Only Embedding<float> is supported as an explicitly configured embedding type.");
        if (property.EmbeddingGenerator is not null && property.EmbeddingGenerator is not IEmbeddingGenerator<string, Embedding<float>>)
            throw new NotSupportedException("The configured embedding generator must support string inputs and Embedding<float> outputs.");
        if (!isDynamic && property.GeneratesVectors && property.EmbeddingGenerator is null)
            throw new NotSupportedException("Typed string vector fields require an IEmbeddingGenerator<string, Embedding<float>>.");
        if (property.DistanceFunction is not (DistanceFunction.CosineSimilarity or DistanceFunction.CosineDistance or
            DistanceFunction.DotProductSimilarity or DistanceFunction.NegativeDotProductSimilarity or
            DistanceFunction.EuclideanDistance or DistanceFunction.EuclideanSquaredDistance))
            throw new NotSupportedException($"Distance function '{property.DistanceFunction}' is not supported.");
        if (property.IndexKind is not null and not IndexKind.Flat and not IndexKind.Hnsw)
            throw new NotSupportedException($"Index kind '{property.IndexKind}' is not supported; use Flat or Hnsw.");
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(property.Dimensions);
    }

    private static MappedProperty ResolveProperty(Type recordType, bool isDynamic, VectorStoreProperty definition,
        IEmbeddingGenerator? defaultGenerator, NullabilityInfoContext nullability)
    {
        PropertyInfo? property = null;
        Type type;
        if (isDynamic)
            type = definition.Type ?? throw new ArgumentException($"Dynamic property '{definition.Name}' must declare its CLR type.", nameof(definition));
        else
        {
            property = recordType.GetProperty(definition.Name, BindingFlags.Public | BindingFlags.Instance);
            if (property is null || (definition.Type is { } declaredType && property.PropertyType != declaredType) ||
                property.GetMethod?.IsPublic != true || property.SetMethod?.IsPublic != true || property.GetIndexParameters().Length != 0)
                throw new ArgumentException($"'{definition.Name}' must identify a public readable/writable property of type '{definition.Type}'.");
            type = property.PropertyType;
        }
        var vector = definition as VectorStoreVectorProperty;
        var nullable = Nullable.GetUnderlyingType(type) is not null ||
            (!type.IsValueType && property is not null && nullability.Create(property).ReadState == NullabilityState.Nullable);
        if (property?.IsDefined(typeof(RequiredMemberAttribute)) == true)
            nullable = false;
        return new(definition.Name, type, property, definition.StorageName ?? definition.Name,
            vector is not null, definition is VectorStoreDataProperty { IsIndexed: true })
        {
            IsNullable = nullable,
            IsFullTextIndexed = definition is VectorStoreDataProperty { IsFullTextIndexed: true },
            Dimensions = vector?.Dimensions ?? 0,
            DistanceFunction = vector?.DistanceFunction ?? DistanceFunction.CosineSimilarity,
            IndexKind = vector?.IndexKind,
            EmbeddingType = vector?.EmbeddingType,
            EmbeddingGenerator = vector is null ? null : vector.EmbeddingGenerator ?? defaultGenerator
        };
    }

    internal static Type? CollectionElementType(Type type) => type.IsArray && type.GetArrayRank() == 1
        ? type.GetElementType()
        : type.IsGenericType && type.GetGenericTypeDefinition() == typeof(List<>) ? type.GenericTypeArguments[0] : null;

    internal static bool IsCollectionType(Type type) => CollectionElementType(type) is not null;

    private static bool IsSupportedDataType(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        type = CollectionElementType(type) ?? type;
        return type == typeof(string) || type == typeof(bool) || type == typeof(int) || type == typeof(long) ||
            type == typeof(float) || type == typeof(double) || type == typeof(DateTime) ||
            type == typeof(DateTimeOffset) || type == typeof(DateOnly);
    }

    /// <summary>Dates use UTC ticks since Unix epoch; DateOnly uses days since Unix epoch.</summary>
    internal static object ToStorageValue(Type type, object value)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        if (!type.IsInstanceOfType(value))
            throw new ArgumentException($"Expected a value of type '{type}'.", nameof(value));
        if (CollectionElementType(type) is { } elementType)
        {
            var collection = (ICollection)value;
            if (IsDateType(elementType))
            {
                var dates = new long[collection.Count];
                var index = 0;
                foreach (var element in collection)
                    dates[index++] = (long)ToStorageValue(elementType, element!);
                return dates;
            }
            if (value is Array array)
                return array.Clone();
            var snapshot = Array.CreateInstance(elementType, collection.Count);
            collection.CopyTo(snapshot, 0);
            return snapshot;
        }
        return value switch
        {
            DateTime date when date.Kind == DateTimeKind.Utc => date.Ticks - DateTime.UnixEpoch.Ticks,
            DateTime => throw new ArgumentException("DateTime data and filter values must have Kind.Utc; use DateTimeOffset for other offsets.", nameof(value)),
            DateTimeOffset date => date.UtcTicks - DateTime.UnixEpoch.Ticks,
            DateOnly date => (long)date.DayNumber - DateOnly.FromDateTime(DateTime.UnixEpoch).DayNumber,
            _ => value
        };
    }

    internal static object? FromStorageValue(Type type, JsonElement value)
    {
        var target = Nullable.GetUnderlyingType(type) ?? type;
        if (value.ValueKind == JsonValueKind.Null)
            return value.Deserialize(type);
        if (CollectionElementType(target) is { } elementType && IsDateType(elementType))
        {
            if (value.ValueKind != JsonValueKind.Array)
                throw new JsonException($"Expected an array for '{type}'.");
            var array = Array.CreateInstance(elementType, value.GetArrayLength());
            var index = 0;
            foreach (var element in value.EnumerateArray())
                array.SetValue(FromStorageValue(elementType, element), index++);
            if (target.IsArray)
                return array;
            var list = (IList)Activator.CreateInstance(target)!;
            foreach (var element in array)
                list.Add(element);
            return list;
        }
        if (!IsDateType(target))
            return value.Deserialize(type);
        try
        {
            var number = value.GetInt64();
            if (target == typeof(DateOnly))
                return DateOnly.FromDayNumber(checked((int)(number + DateOnly.FromDateTime(DateTime.UnixEpoch).DayNumber)));
            var date = new DateTime(checked(number + DateTime.UnixEpoch.Ticks), DateTimeKind.Utc);
            return target == typeof(DateTime) ? date : (object)new DateTimeOffset(date);
        }
        catch (Exception exception) when (exception is ArgumentException or OverflowException or FormatException or InvalidOperationException)
        {
            throw new JsonException($"Invalid stored date for '{type}'.", exception);
        }
    }

    private static bool IsDateType(Type type) => type == typeof(DateTime) || type == typeof(DateTimeOffset) || type == typeof(DateOnly);

    private static List<VectorStoreProperty> DiscoverProperties(Type recordType)
    {
        List<VectorStoreProperty> result = [];
        foreach (var property in recordType.GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.GetCustomAttribute<VectorStoreKeyAttribute>() is { } key)
                result.Add(new VectorStoreKeyProperty(property.Name, property.PropertyType)
                {
                    StorageName = key.StorageName,
                    IsAutoGenerated = key.IsAutoGenerated
                });
            if (property.GetCustomAttribute<VectorStoreDataAttribute>() is { } data)
                result.Add(new VectorStoreDataProperty(property.Name, property.PropertyType)
                {
                    StorageName = data.StorageName,
                    IsIndexed = data.IsIndexed,
                    IsFullTextIndexed = data.IsFullTextIndexed
                });
            if (property.GetCustomAttribute<VectorStoreVectorAttribute>() is { } vector)
                result.Add(new VectorStoreVectorProperty(property.Name, property.PropertyType, vector.Dimensions)
                {
                    StorageName = vector.StorageName,
                    DistanceFunction = vector.DistanceFunction,
                    IndexKind = vector.IndexKind
                });
        }
        return result;
    }

    internal sealed record MappedProperty(string Name, Type Type, PropertyInfo? Property, string StorageName, bool IsVector, bool IsFilterable)
    {
        internal bool IsNullable { get; init; }
        internal bool IsFullTextIndexed { get; init; }
        internal int Dimensions { get; init; }
        internal string DistanceFunction { get; init; } = Microsoft.Extensions.VectorData.DistanceFunction.CosineSimilarity;
        internal string? IndexKind { get; init; }
        internal Type? EmbeddingType { get; init; }
        internal IEmbeddingGenerator? EmbeddingGenerator { get; init; }
        internal bool GeneratesVectors => IsVector && Type == typeof(string);
    }
}
